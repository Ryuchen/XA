const path = require('node:path')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const { pathToFileURL } = require('node:url')
const { chromium } = require('../../node_modules/playwright')
const root = __dirname
;(async () => {
  const browser = await chromium.launch({ headless: true })
  const result = { checks: [], errors: [], network: [], passed: false }
  try {
    const page = await browser.newPage({ viewport: { width: 1366, height: 1024 } })
    page.on('pageerror', error => result.errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') result.errors.push(message.text()) })
    page.on('request', request => { if (/^https?:/.test(request.url())) result.network.push(request.url()) })
    await page.goto(pathToFileURL(path.join(root, 'dir-1.html')).href)
    await page.locator('.record-table').waitFor()
    assert.equal(await page.locator('#rail-navigation .domain-trigger').count(), 9)
    assert.equal(await page.locator('#platform-navigation .domain-trigger').count(), 1)
    assert.equal(await page.locator('#navigation [data-admin-secondary-nav="orders"]').count(), 1)
    assert.equal(await page.locator('.topbar .search-trigger').count(), 0)
    assert.equal(await page.locator('#sidebar-search-input').isVisible(), true)
    assert.equal(await page.locator('#rail-navigation .page-title').first().evaluate(element => getComputedStyle(element).display), 'none')
    assert.equal(await page.locator('.sidebar').evaluate(element => Math.round(element.getBoundingClientRect().width)), 288)
    await page.screenshot({ path: path.join(root, 'dir-1.png'), animations: 'disabled' })
    result.checks.push('一级图标轨与二三级面板结构正确')

    await page.goto(`${pathToFileURL(path.join(root, 'dir-1.html')).href}#/dashboard`)
    assert.equal(await page.locator('#app').evaluate(element => element.classList.contains('is-collapsed')), true)
    assert.equal(await page.locator('.sidebar-panel').isVisible(), false)
    assert.equal(await page.locator('#navigation [data-admin-secondary-nav]').count(), 0)
    await page.screenshot({ path: path.join(root, 'dir-1-home.png'), animations: 'disabled' })
    await page.locator('[data-domain="orders"]').click()
    await page.locator('.record-table').waitFor()
    await page.locator('.sidebar-panel').waitFor({ state: 'visible' })
    assert.equal(await page.locator('.sidebar-panel').isVisible(), true)
    result.checks.push('工作台为独立首页，无二级目录')

    await page.locator('#sidebar-search-input').fill('统一字典')
    assert.equal(await page.locator('.search-result').count(), 1)
    await page.locator('.search-result').click()
    assert.ok(page.url().endsWith('#/dictionaries'))
    assert.equal(await page.locator('#sidebar-search-input').inputValue(), '')
    assert.equal(await page.locator('#navigation [data-admin-secondary-nav="system"]').count(), 1)
    result.checks.push('面板搜索、结果跳转和当前模块恢复正确')

    await page.locator('#quick-dispatch').click()
    assert.equal(await page.locator('#quick-dialog').evaluate(dialog => dialog.open), true)
    await page.locator('#quick-close').click()
    await page.locator('#collapse').click()
    assert.equal(await page.locator('#app').evaluate(element => element.classList.contains('is-collapsed')), true)
    assert.equal(await page.locator('.sidebar-panel').isVisible(), false)
    assert.equal(await page.locator('#quick-rail').isVisible(), true)
    await page.waitForFunction(() => Math.round(document.querySelector('.sidebar').getBoundingClientRect().width) === 72)
    assert.equal(await page.locator('.sidebar').evaluate(element => Math.round(element.getBoundingClientRect().width)), 72)
    await page.screenshot({ path: path.join(root, 'dir-1-rail-collapsed.png'), animations: 'disabled' })
    assert.equal(await page.locator('#search-rail').isVisible(), true)
    await page.locator('#quick-rail').click()
    assert.equal(await page.locator('#quick-dialog').evaluate(dialog => dialog.open), true)
    await page.locator('#quick-close').click()
    await page.locator('#collapse').click()
    await page.locator('#search-rail').click()
    assert.equal(await page.locator('#sidebar-search-input').evaluate(element => document.activeElement === element), true)
    result.checks.push('收起态快捷派单与搜索图标可展开面板')
    await page.locator('[data-domain="orders"]').click()
    await page.locator('.record-table').waitFor()
    assert.equal(await page.locator('.sidebar-panel').isVisible(), true)
    result.checks.push('面板收起、图标快捷派单及点击图标恢复面板正确')

    await page.keyboard.press('Control+k')
    assert.equal(await page.locator('#sidebar-search-input').evaluate(element => document.activeElement === element), true)
    await page.setViewportSize({ width: 1920, height: 1080 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 1920)
    await page.setViewportSize({ width: 375, height: 812 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 375)
    await page.locator('#mobile-toggle').click()
    await page.waitForFunction(() => Math.abs(document.querySelector('.sidebar').getBoundingClientRect().x) < 1)
    assert.equal(await page.locator('#sidebar-search-input').isVisible(), true)
    result.checks.push('快捷键聚焦、1920桌面与375窄屏导航可用')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    assert.equal(await page.locator('.sidebar-panel').evaluate(element => getComputedStyle(element).animationName), 'none')
    assert.ok(await page.locator('#quick-dispatch svg').first().evaluate(element => parseFloat(getComputedStyle(element).transitionDuration) <= 0.001))
    result.checks.push('减少动态效果模式关闭动画')
    assert.deepEqual(result.errors, [])
    assert.deepEqual(result.network, [])
    result.passed = true
    await page.close()
  } catch (error) {
    result.error = error.stack
  } finally {
    await browser.close()
  }
  fs.writeFileSync(path.join(root, 'rail-verification.json'), JSON.stringify(result, null, 2))
  console.log(JSON.stringify(result, null, 2))
  if (!result.passed) process.exitCode = 1
})()
