const test = require('node:test')
const assert = require('node:assert/strict')
const { environment, watch } = require('./test-auth-sessions.cjs')

test('silent background errors remain retryable without repeated popups', async () => {
  const s = environment('admin'); s.login('A')
  const network = watch(s.api.request({ url: '/orders/', silent: true }))
  const first = await s.issued(0)
  first.reject(Object.assign(new Error('network failure'), { config: first.config }))
  assert((await network).error)
  assert.equal(s.notices.length, 0)
  assert.equal(s.token(), 'token-A')
  const business = watch(s.api.request({ url: '/orders/', silent: true }))
  s.respond(await s.issued(1), 200, { code: 400, msg: 'temporary error' })
  assert((await business).error)
  assert.equal(s.notices.length, 0)
  const normal = watch(s.api.request({ url: '/orders/' }))
  s.respond(await s.issued(2), 503, { code: 503, msg: 'visible error' })
  assert((await normal).error)
  assert.deepEqual(s.notices, ['visible error'])
})

test('silent requests still refresh and clear a definitively expired session', async () => {
  const s = environment('admin'); s.login('A')
  const pending = watch(s.api.request({ url: '/orders/', silent: true }))
  s.respond(await s.issued(0), 401)
  s.respond(await s.issued(1), 401, { code: 401 })
  assert((await pending).error)
  assert.equal(s.token(), '')
  assert.equal(s.navigation.length, 1)
  assert.equal(s.notices.length, 1)
})
