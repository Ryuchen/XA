// Independent platform session, real browser and isolated ASGI.
const fs = require('node:fs')
const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const input = JSON.parse(fs.readFileSync(0, 'utf8'))
;(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-proxy-server'] })
  try {
    const context = await browser.newContext({ viewport: { width: 1366, height: 1024 } })
    await context.addInitScript(user => sessionStorage.setItem('xa:fronted:platform:session:v1', JSON.stringify({
      token: user.token, refresh: user.refresh, sessionId: 'platform-store-browser',
      profile: { id: user.id, username: user.username, identity_type: 'platform', grants: [{ role: 'SUPER_ADMIN', scope_slug: '*' }] },
    })), input)
    const page = await context.newPage(), errors = [], managementResponses = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('response', response => { if (new URL(response.url()).pathname.includes('store-management')) managementResponses.push(response.status()) })
    await page.route(url => url.pathname.startsWith('/api/'), async route => {
      try {
        const target = new URL(route.request().url())
        // The test exercises real store-management APIs; unrelated finance
        // dashboard reads write audit rows and contend with SQLite migrations.
        if (target.pathname.replace(/\/$/, '') === '/api/admin/platform/withdrawals') {
          return route.fulfill({ status: 200, contentType: 'application/json',
            body: JSON.stringify({ code: 0, data: { stores: [], read_at: new Date().toISOString() } }) })
        }
        const response = await route.fetch({ url: input.api + target.pathname + target.search,
          headers: { ...route.request().headers(), host: 'admin.esports.club' }, timeout: 70000 })
        await route.fulfill({ response })
      } catch (error) {
        if (!/already handled|Request context disposed|Target page, context or browser has been closed/i.test(String(error)))
          errors.push('isolated API proxy failed')
      }
    })
    await page.goto('http://admin.esports.club/#/')
    process.stdout.write('opened platform\n')
    const section = page.locator('section').filter({ has: page.getByRole('heading', { name: '门店管理', exact: true }) })
    await section.getByRole('button', { name: '新增门店' }).click()
    const form = section.locator('form')
    await form.getByLabel('门店名称', { exact: true }).fill('页面测试新店')
    await form.getByLabel('门店标识（小写）').fill('platform-browser-store')
    await form.getByLabel('实体编号前缀').fill('PB')
    await form.getByLabel('陪玩展示简称（英文）').fill('pb')
    await form.getByLabel('店币名称').fill('测试币')
    await form.getByLabel('已配置的独立业务库').selectOption('store_new')
    await form.getByLabel('账号', { exact: true }).fill('page-store-admin')
    await form.getByLabel('昵称', { exact: true }).fill('测试管理员')
    await form.getByLabel('密码', { exact: true }).fill('Synthetic-Store-Administrator-2026!')
    await form.getByLabel('手机号', { exact: true }).fill('13800002222')
    await form.getByRole('button', { name: '创建并初始化' }).click()
    process.stdout.write('submitted creation\n')
    try {
      await section.getByRole('row').filter({ hasText: '页面测试新店' }).getByText('待配置').waitFor({ timeout: 65000 })
    } catch {
      throw new Error(`创建后页面未显示待配置：接口状态 ${managementResponses.join(',')}；页面文字 ${await section.innerText()}`)
    }
    process.stdout.write('created store\n')
    await section.getByRole('row').filter({ hasText: '页面测试新店' }).getByRole('button', { name: '编辑' }).click()
    await section.locator('form').getByLabel('门店名称', { exact: true }).fill('页面测试新店已更新')
    await section.locator('form').getByLabel('陪玩展示简称（英文）').fill('px')
    await section.locator('form').getByRole('button', { name: '保存', exact: true }).click()
    await section.getByRole('row').filter({ hasText: '页面测试新店已更新' }).getByText('待配置').waitFor()
    process.stdout.write('updated store\n')
    await section.getByRole('row').filter({ hasText: '页面测试新店已更新' }).getByRole('button', { name: '配置核对' }).click()
    const setup = page.getByRole('dialog').first()
    if (input.points_usage) {
      await setup.getByLabel('每组积分').fill('100.25')
      await setup.getByLabel('每组抵扣测试币（整数）').fill('3')
      await setup.getByLabel('单笔最高抵扣比例（%）').fill('45.55')
      await setup.getByRole('button', { name: '保存积分规则' }).click()
      await page.getByRole('dialog', { name: '确认积分抵扣规则' }).getByRole('button', { name: '确认', exact: true }).click()
      await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent?.trim() === '保存积分规则' && button.disabled))
      await setup.getByRole('switch', { name: '积分抽奖' }).click()
      await setup.getByRole('button', { name: '保存积分开关' }).click()
      await page.getByRole('dialog', { name: '确认积分使用开关' }).getByRole('button', { name: '确认', exact: true }).click()
      await setup.getByText('当前积分使用：暂停；任一项停用时全部暂停使用。').waitFor()
      process.stdout.write('configured points rules and usage\n')
    }
    if (input.monthly_cutover) {
      await setup.getByRole('button', { name: '核对切换规则' }).click()
      const monthly = page.getByRole('dialog', { name: '确认切换会员月券' })
      await monthly.getByText(/按已发 0 张处理/).waitFor()
      await monthly.getByRole('button', { name: '确认', exact: true }).click()
      await setup.getByText(/已切换：/).waitFor()
      assert.equal(await setup.getByRole('button', { name: '核对切换规则' }).count(), 0)
      process.stdout.write('configured monthly cutover\n')
    }
    await setup.getByLabel('每位陪玩同时接单上限').fill('4')
    await setup.getByRole('button', { name: '保存名额' }).click()
    await page.getByRole('dialog').last().getByRole('button', { name: '确认', exact: true }).click()
    const capacity = setup.getByRole('row').filter({ hasText: '陪玩接单名额' })
    await capacity.getByText('已保存', { exact: true }).waitFor()
    await capacity.getByRole('button', { name: '核对并确认' }).click()
    const confirm = page.getByRole('dialog').last()
    await confirm.getByText('4 单', { exact: true }).waitFor()
    await confirm.getByRole('button', { name: '确认', exact: true }).click()
    await capacity.getByText('已确认', { exact: true }).waitFor()
    process.stdout.write('configured and confirmed capacity\n')
    await setup.getByLabel('售后等待（小时）').fill('48')
    await setup.getByLabel('收益冻结（小时）').fill('36')
    await setup.getByRole('button', { name: '保存时限' }).click()
    await page.getByRole('dialog').last().getByRole('button', { name: '确认', exact: true }).click()
    const clocks = setup.getByRole('row').filter({ hasText: '售后及收益冻结时限' })
    await clocks.getByText('已保存', { exact: true }).waitFor()
    await clocks.getByRole('button', { name: '核对并确认' }).click()
    await page.getByRole('dialog').last().getByRole('button', { name: '确认', exact: true }).click()
    await clocks.getByText('已确认', { exact: true }).waitFor()
    process.stdout.write('configured and confirmed clocks\n')
    await setup.getByLabel('现金押金目标（测试币）').fill('5000')
    await setup.getByLabel('单抵押金目标（测试币）').fill('9000')
    await setup.getByRole('button', { name: '保存押金目标' }).click()
    await page.getByRole('dialog').last().getByRole('button', { name: '确认', exact: true }).click()
    const targets = setup.getByRole('row').filter({ hasText: '现金及单抵押金目标' })
    await targets.getByText('已保存', { exact: true }).waitFor()
    await targets.getByRole('button', { name: '核对并确认' }).click()
    await page.getByRole('dialog').last().getByRole('button', { name: '确认', exact: true }).click()
    await targets.getByText('已确认', { exact: true }).waitFor()
    await setup.getByLabel('单抵比例（%）').fill('55')
    await setup.getByRole('button', { name: '保存单抵比例' }).click()
    await page.getByRole('dialog').last().getByRole('button', { name: '确认', exact: true }).click()
    const percent = setup.getByRole('row').filter({ hasText: '单抵押金比例' })
    await percent.getByRole('button', { name: '核对并确认' }).click()
    await page.getByRole('dialog').last().getByRole('button', { name: '确认', exact: true }).click()
    await percent.getByText('已确认', { exact: true }).waitFor()
    process.stdout.write('configured and confirmed deposit rules\n')
    await setup.getByLabel('提现单笔最低额（测试币）').fill('100')
    await setup.getByLabel('提现余额门槛（测试币）').fill('500')
    await setup.getByLabel('提现费率（%）').fill('3')
    await setup.getByRole('button', { name: '保存提现规则' }).click()
    await page.getByRole('dialog').last().getByRole('button', { name: '确认', exact: true }).click()
    const withdraw = setup.getByRole('row').filter({ hasText: '提现规则' })
    await withdraw.getByRole('button', { name: '核对并确认' }).click()
    await page.getByRole('dialog').last().getByRole('button', { name: '确认', exact: true }).click()
    await withdraw.getByText('已确认', { exact: true }).waitFor()
    process.stdout.write('configured and confirmed withdrawal rules\n')
    await page.unrouteAll({ behavior: 'ignoreErrors' })
    assert.deepEqual(errors, [])
    await context.close()
  } finally { await browser.close() }
})().catch(error => { console.error(error.stack || error); process.exitCode = 1 })
