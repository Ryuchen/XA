import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

// Sass and WXSS consume the same literal color declarations. No build-time
// dependency is needed inside the native WeChat package.
const root = resolve(import.meta.dirname, '..')
const source = await readFile(resolve(root, 'packages/design-system/src/_theme.scss'), 'utf8')
const light = source.match(/@mixin light\s*\{([\s\S]*?)\n\}/)?.[1]
if (!light) throw new Error('Shared light theme is missing')
const declarations = [...light.matchAll(/(--xa-[\w-]+)\s*:\s*([^;]+);/g)]
if (!declarations.length) throw new Error('Shared light theme has no declarations')
const values = new Map(declarations.map(([, name, value]) => [name, value.trim()]))
function literal(name, seen = new Set()) {
  if (seen.has(name) || !values.has(name)) throw new Error('Unresolved theme token: ' + name)
  seen.add(name)
  return values.get(name).replace(/var\((--xa-[\w-]+)\)/g, (_, token) => literal(token, new Set(seen)))
}
const nativeRoot = resolve(root, 'apps/boss-miniapp/native')
const themePath = resolve(nativeRoot, 'theme.wxss')
const theme = '/* Generated by scripts/sync-native-theme.mjs from the shared light theme. */\npage {\n'
  + declarations.map(([, name, value]) => `  ${name}: ${value.trim().replace(/\s+/g, ' ')};`).join('\n') + '\n}\n'
const manifestPath = resolve(nativeRoot, 'app.json')
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
manifest.window.navigationBarBackgroundColor = literal('--xa-color-surface-page')
manifest.window.backgroundColor = literal('--xa-color-surface-page')
manifest.tabBar.color = literal('--xa-color-text-secondary')
manifest.tabBar.selectedColor = literal('--xa-color-primary')
manifest.tabBar.backgroundColor = literal('--xa-color-surface-card')
const manifestText = JSON.stringify(manifest, null, 2) + '\n'
if (process.argv.includes('--check')) {
  if ((await readFile(themePath, 'utf8')).replace(/\r\n/g, '\n') !== theme || (await readFile(manifestPath, 'utf8')).replace(/\r\n/g, '\n') !== manifestText) {
    throw new Error('Native theme is stale. Run node scripts/sync-native-theme.mjs')
  }
  console.log('Native and shared theme tokens match.')
} else {
  await writeFile(themePath, theme)
  await writeFile(manifestPath, manifestText)
  console.log('Synced native theme and navigation colors.')
}
