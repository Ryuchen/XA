import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

// Sass and WXSS consume the same literal color declarations. No build-time
// dependency is needed inside the native WeChat package.
const root = resolve(import.meta.dirname, '..')
const source = await readFile(resolve(root, 'packages/design-system/src/_theme.scss'), 'utf8')
const light = source.match(/@mixin light\s*\{([\s\S]*?)\n\}/)?.[1]
if (!light) throw new Error('Shared light theme is missing')
const declarations = [...light.matchAll(/(--xa-[\w-]+)\s*:\s*([^;]+);/g)]
if (!declarations.length) throw new Error('Shared light theme has no declarations')
const values = new Map(declarations.map(([, name, value]) => [name, value.trim()]))
function literal(name, seen = new Set()) {
  if (seen.has(name) || !values.has(name)) throw new Error('Unresolved theme token: ' + name)
  seen.add(name)
  return values.get(name).replace(/var\((--xa-[\w-]+)\)/g, (_, token) => literal(token, new Set(seen)))
}
const nativeRoot = resolve(root, 'apps/boss-miniapp/native')
const themePath = resolve(nativeRoot, 'theme.wxss')
const theme = '/* Generated by scripts/sync-native-theme.mjs from the shared light theme. */\npage {\n'
  + declarations.map(([, name, value]) => `  ${name}: ${value.trim().replace(/\s+/g, ' ')};`).join('\n') + '\n}\n'
const manifestPath = resolve(nativeRoot, 'app.json')
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
manifest.window.navigationBarBackgroundColor = literal('--xa-color-surface-page')
manifest.window.backgroundColor = literal('--xa-color-surface-page')
manifest.tabBar.color = literal('--xa-color-text-secondary')
manifest.tabBar.selectedColor = literal('--xa-color-primary')
manifest.tabBar.backgroundColor = literal('--xa-color-surface-card')
const manifestText = JSON.stringify(manifest, null, 2) + '\n'
// Native widget attributes and data-URI icons cannot inherit CSS variables.
const palette = { primary: literal('--xa-color-primary'), secondary: literal('--xa-color-text-secondary'),
  onPrimary: literal('--xa-color-on-primary'), page: literal('--xa-color-surface-page'), card: literal('--xa-color-surface-card') }
const palettePath = resolve(root, 'apps/provider-miniapp/src/styles/nativeColors.ts')
const paletteText = '// Generated by scripts/sync-native-theme.mjs; edit the shared theme.\nexport const nativeColors = ' + JSON.stringify(palette, null, 2) + ' as const;\n'
const nativePalettePath = resolve(nativeRoot, 'core/theme.js')
const nativePaletteText = '// Generated by scripts/sync-native-theme.mjs; edit the shared theme.\nmodule.exports = ' + JSON.stringify(palette, null, 2) + ';\n'
const providerThemePath = resolve(root, 'apps/provider-miniapp/src/theme.json')
const providerTheme = JSON.parse(await readFile(providerThemePath, 'utf8'))
for (const mode of Object.values(providerTheme)) { mode.navBgColor = palette.card; mode.bgColor = palette.page }
const providerThemeText = JSON.stringify(providerTheme, null, 2) + '\n'
const priorPalette = await readFile(nativePalettePath, 'utf8').catch(() => '')
const priorPrimary = priorPalette.match(/"primary":\s*"(#[a-f\d]{6})"/i)?.[1]
const managedPrimary = [...new Set(['#136398', palette.primary, priorPrimary].filter(Boolean))].join('|')
const primaryAttribute = new RegExp('((?:color|activeColor|indicator-active-color)=")(' + managedPrimary + ')"', 'g')
const nativeWidgets = []
for (const page of manifest.pages) {
  const file = resolve(nativeRoot, page + '.wxml')
  const original = await readFile(file, 'utf8')
  const updated = original.replace(primaryAttribute, '$1' + palette.primary + '"')
  nativeWidgets.push([file, original, updated])
}
if (process.argv.includes('--check')) {
  if ((await readFile(themePath, 'utf8')).replace(/\r\n/g, '\n') !== theme || (await readFile(manifestPath, 'utf8')).replace(/\r\n/g, '\n') !== manifestText) {
    throw new Error('Native theme is stale. Run node scripts/sync-native-theme.mjs')
  }
  for (const [file, original, expected] of nativeWidgets) if (original !== expected) throw new Error('Native widget color is stale: ' + file)
  if ((await readFile(providerThemePath, 'utf8')).replace(/\r\n/g, '\n') !== providerThemeText) throw new Error('Provider native theme is stale. Run node scripts/sync-native-theme.mjs')
  if ((await readFile(palettePath, 'utf8')).replace(/\r\n/g, '\n') !== paletteText || (await readFile(nativePalettePath, 'utf8')).replace(/\r\n/g, '\n') !== nativePaletteText) throw new Error('Native icon palette is stale. Run node scripts/sync-native-theme.mjs')
  console.log('Native and shared theme tokens match.')
} else {
  await writeFile(themePath, theme)
  await writeFile(manifestPath, manifestText)
  await writeFile(palettePath, paletteText)
  await writeFile(nativePalettePath, nativePaletteText)
  await writeFile(providerThemePath, providerThemeText)
  for (const [file, original, expected] of nativeWidgets) if (original !== expected) await writeFile(file, expected)
  console.log('Synced native theme and navigation colors.')
}
