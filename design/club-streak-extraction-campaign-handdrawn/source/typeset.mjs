import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {makeLayout} from '../layout-adapter.mjs';
import {renderProject} from './render.mjs';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read=async p=>JSON.parse((await fs.readFile(p,'utf8')).replace(/^\uFEFF/,''));
const hash=s=>createHash('sha256').update(s).digest('hex');
const state=await read(path.join(root,'campaign-state.json'));
state.approvals.background={...state.approvals.background,status:'approved',basis:'用户在七张底图和文字位置稿交付后回复：继续'};
state.stage='vector-production';state.revision='streak-r3-route';
state.typographyPreference={basis:'用户反馈：文字太大了，要保留文字与所在区块的上下间距',bodyFont:'Microsoft YaHei UI Bold',layout:'缩小字号，重新测量可见字形并整组居中'};
await fs.writeFile(path.join(root,'campaign-state.json'),JSON.stringify(state,null,2));
const content=await read(path.join(root,'content.json')),metrics=await read(path.join(root,'02-layouts/generated-background-measurements.json'));
const draft=makeLayout(content,metrics);
await fs.mkdir(path.join(root,'.cache'),{recursive:true});
const input=path.join(root,'.cache','all-text-requests.json'),output=path.join(root,'.cache','all-text-outlines.json');
await fs.writeFile(input,JSON.stringify(draft.requests));
const outlineHash=hash(JSON.stringify(draft.requests)),stamp=path.join(root,'.cache/text-request-hash.txt');
let cachedHash='';try{cachedHash=await fs.readFile(stamp,'utf8');}catch{}
if(cachedHash!==outlineHash){console.log(execFileSync('powershell.exe',['-NoProfile','-ExecutionPolicy','Bypass','-File',path.join(root,'source/outline-text.ps1'),'-InputFile',input,'-OutputFile',output],{encoding:'utf8'}).trim());await fs.writeFile(stamp,outlineHash);}else console.log('复用字体轮廓缓存。');
const glyphs=await read(output);
const plan=makeLayout(content,metrics,glyphs);
const cache={};for(const r of plan.requests)cache[hash(JSON.stringify([r.text,r.font,r.style]))]=glyphs[r.id];
await fs.writeFile(path.join(root,'.cache/font-outlines.json'),JSON.stringify(cache));
await fs.writeFile(path.join(root,'layout.json'),JSON.stringify(plan,null,2));
await fs.writeFile(path.join(root,'review/typesetting-placements.json'),JSON.stringify(plan.placements,null,2));
const only=process.argv.find(v=>v.startsWith('--only='))?.slice(7);
await renderProject(root,{only});
console.log('完成文字转曲与指定页面导出。');
