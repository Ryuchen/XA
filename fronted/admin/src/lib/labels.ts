export function enumLabel(value: unknown) {
  if (value == null || value === "") return "—"
  return labels[String(value)] || String(value)
}
export function isEnumField(key: string) {
  return /(?:status|kind|scope|audience|route|policy|platform|grade|gender|payment|source|mode|tier)$/.test(
    key
  )
}
